.section .text
.globl _start

_start:

    # ==========================================
    # 1. ADD / SUB
    # ==========================================

    addi x1, x0, 10          # x1 = 10
    addi x2, x0, 3           # x2 = 3

    add  x3, x1, x2          # x3 = 13
    sub  x4, x1, x2          # x4 = 7


    # ==========================================
    # 2. AND / OR / XOR
    # ==========================================

    and  x5, x1, x2          # x5 = 10 & 3 = 2
    or   x6, x1, x2          # x6 = 10 | 3 = 11
    xor  x7, x1, x2          # x7 = 10 ^ 3 = 9


    # ==========================================
    # 3. ADDI / ANDI / ORI
    # ==========================================

    addi x8, x1, 5           # x8 = 15
    andi x9, x1, 3           # x9 = 2
    ori  x10, x2, 8          # x10 = 11


    # ==========================================
    # 4. LUI
    # ==========================================

    lui  x11, 0x12345        # x11 = 0x12345000


    # ==========================================
    # 5. SW / LW
    # ==========================================

    addi x12, x0, 100        # x12 = memory address 100
    sw   x3, 0(x12)          # memory[100] = 13
    lw   x13, 0(x12)         # x13 = 13


    # ==========================================
    # 6. BEQ
    # ==========================================

    addi x14, x0, 20
    addi x15, x0, 20

    beq  x14, x15, beq_taken

    # This instruction should NOT execute
    addi x16, x0, 99

beq_taken:

    addi x16, x0, 42         # x16 = 42


    # ==========================================
    # 7. BNE
    # ==========================================

    addi x17, x0, 20
    addi x18, x0, 30

    bne  x17, x18, bne_taken

    # This instruction should NOT execute
    addi x19, x0, 99

bne_taken:

    addi x19, x0, 55         # x19 = 55


    # ==========================================
    # 8. JAL
    # ==========================================

    jal  x20, jal_target

    # This instruction should NOT execute
    addi x21, x0, 99

jal_target:

    addi x21, x0, 77         # x21 = 77


    # ==========================================
    # END: infinite loop
    # ==========================================

end:
    jal  x0, end
